static int tp_lines_valid(const tp_line *lines, size_t line_count)
{
    size_t i, j;
    if (line_count > TP_MAX_LINES) return 0;
    if (line_count > 0 && lines == NULL) return 0;
    for (i = 0; i < line_count; i++) {
        if (lines[i].length > TP_MAX_LINE_LENGTH) return 0;
        if (lines[i].length > 0 && lines[i].text == NULL) return 0;
        for (j = 0; j < lines[i].length; j++) {
            unsigned char b = lines[i].text[j];
            if (b < 0x20u || b > 0x7eu) return 0;
        }
    }
    return 1;
}

tp_result tp_render(uint32_t *pixels, size_t capacity_pixels,
                    size_t width, size_t height, size_t stride_pixels,
                    const tp_line *lines, size_t line_count,
                    uint32_t foreground, uint32_t background)
{
    size_t x, y, i, j, r, c;

    if (pixels == NULL) return TP_INVALID;
    if (width < 1 || width > TP_MAX_DIMENSION) return TP_INVALID;
    if (height < 1 || height > TP_MAX_DIMENSION) return TP_INVALID;
    if (stride_pixels < width || stride_pixels > TP_MAX_DIMENSION) return TP_INVALID;
    if (height - 1 > (SIZE_MAX - width) / stride_pixels) return TP_INVALID;
    if (capacity_pixels < (height - 1) * stride_pixels + width) return TP_INVALID;
    if (!tp_lines_valid(lines, line_count)) return TP_INVALID;

    for (y = 0; y < height; y++)
        for (x = 0; x < width; x++)
            pixels[y * stride_pixels + x] = background;

    for (i = 0; i < line_count; i++) {
        size_t y0 = i * TP_CELL_HEIGHT;
        if (y0 >= height) break;
        for (j = 0; j < lines[i].length; j++) {
            size_t x0 = j * TP_CELL_WIDTH;
            const unsigned char *g;
            if (x0 >= width) break;
            g = tp_font[lines[i].text[j] - 0x20u];
            for (r = 0; r < 7 && y0 + r < height; r++)
                for (c = 0; c < 5 && x0 + c < width; c++)
                    if ((g[r] >> (4 - c)) & 1u)
                        pixels[(y0 + r) * stride_pixels + x0 + c] = foreground;
        }
    }
    return TP_OK;
}
